/**
 * MarrowScript Structured Output Parser
 *
 * Generates a robust runtime output parser that handles:
 *   1. Markdown fence extraction (```json, ```ts, bare ```)
 *   2. Partial/malformed JSON repair (trailing commas, unquoted keys, truncation)
 *   3. Typed Zod validation against the declared `returns:` shape
 *   4. Multiple extraction strategies (fence → raw parse → regex extract → repair)
 *   5. Detailed error reporting for repair prompts
 *
 * This replaces the simple JSON.parse() fallback with a multi-strategy pipeline:
 *   Strategy 1: Direct JSON.parse (fastest path — model returned clean JSON)
 *   Strategy 2: Fence extraction + JSON.parse
 *   Strategy 3: Regex extraction (find first { or [ in the response)
 *   Strategy 4: JSON repair (fix common LLM mistakes)
 *   Strategy 5: Return raw with error context (for repair prompt)
 */

import * as IR from "./ir";
import { EmittedFile } from "./emitter";

/**
 * Emit the output parser runtime module: src/cognition/output_parser.ts
 */
export function emitOutputParser(system: IR.IRSystem): EmittedFile | null {
  // Only emit if there are prompts that return JSON
  const jsonPrompts = system.prompts.filter(p =>
    p.output_type !== "string" || p.validate.kind === "schema_only"
  );
  if (jsonPrompts.length === 0) return null;

  const lines: string[] = [];
  lines.push("// Generated by MarrowScript compiler. DO NOT EDIT.");
  lines.push("// Structured Output Parser — robust extraction + validation.");
  lines.push("//");
  lines.push("// Multi-strategy parsing pipeline:");
  lines.push("//   1. Direct JSON.parse");
  lines.push("//   2. Fence extraction + parse");
  lines.push("//   3. Regex extraction (first { or [)");
  lines.push("//   4. JSON repair (trailing commas, unquoted keys, truncation)");
  lines.push("//   5. Failure with diagnostics");
  lines.push("");
  lines.push("import { z } from \"zod\";");
  lines.push("");

  // ─── Core parse function ─────────────────────────────────────────────
  lines.push("export interface ParseResult<T> {");
  lines.push("  success: boolean;");
  lines.push("  data: T | null;");
  lines.push("  raw: string;");
  lines.push("  strategy: string;");
  lines.push("  errors: string[];");
  lines.push("}");
  lines.push("");

  lines.push("/**");
  lines.push(" * Parse model output into a typed result.");
  lines.push(" * Tries multiple strategies in order, returns the first success.");
  lines.push(" */");
  lines.push("export function parseStructuredOutput<T>(");
  lines.push("  raw: string,");
  lines.push("  schema: z.ZodType<T>,");
  lines.push("  mode: \"json\" | \"string\" | \"file\" | \"files\" = \"json\"");
  lines.push("): ParseResult<T> {");
  lines.push("  if (mode === \"string\") {");
  lines.push("    const extracted = extractLargestFencedBlock(raw);");
  lines.push("    return { success: true, data: extracted as unknown as T, raw, strategy: \"string_fence\", errors: [] };");
  lines.push("  }");
  lines.push("");
  lines.push("  const errors: string[] = [];");
  lines.push("");
  lines.push("  // Strategy 1: Direct JSON.parse");
  lines.push("  try {");
  lines.push("    const parsed = JSON.parse(raw);");
  lines.push("    const result = schema.safeParse(parsed);");
  lines.push("    if (result.success) return { success: true, data: result.data, raw, strategy: \"direct_parse\", errors: [] };");
  lines.push("    errors.push(`direct_parse: schema validation failed — ${formatZodError(result.error)}`);");
  lines.push("  } catch (e: any) {");
  lines.push("    errors.push(`direct_parse: ${e.message}`);");
  lines.push("  }");
  lines.push("");
  lines.push("  // Strategy 2: Fence extraction + parse");
  lines.push("  const fenced = extractJsonFence(raw);");
  lines.push("  if (fenced) {");
  lines.push("    try {");
  lines.push("      const parsed = JSON.parse(fenced);");
  lines.push("      const result = schema.safeParse(parsed);");
  lines.push("      if (result.success) return { success: true, data: result.data, raw, strategy: \"fence_extract\", errors: [] };");
  lines.push("      errors.push(`fence_extract: schema validation failed — ${formatZodError(result.error)}`);");
  lines.push("    } catch (e: any) {");
  lines.push("      errors.push(`fence_extract: ${e.message}`);");
  lines.push("    }");
  lines.push("  }");
  lines.push("");
  lines.push("  // Strategy 3: Regex extraction (find first { or [)");
  lines.push("  const extracted = extractJsonFromProse(raw);");
  lines.push("  if (extracted) {");
  lines.push("    try {");
  lines.push("      const parsed = JSON.parse(extracted);");
  lines.push("      const result = schema.safeParse(parsed);");
  lines.push("      if (result.success) return { success: true, data: result.data, raw, strategy: \"regex_extract\", errors: [] };");
  lines.push("      errors.push(`regex_extract: schema validation failed — ${formatZodError(result.error)}`);");
  lines.push("    } catch (e: any) {");
  lines.push("      errors.push(`regex_extract: ${e.message}`);");
  lines.push("    }");
  lines.push("  }");
  lines.push("");
  lines.push("  // Strategy 4: JSON repair");
  lines.push("  const repaired = repairJson(fenced || extracted || raw);");
  lines.push("  if (repaired) {");
  lines.push("    try {");
  lines.push("      const parsed = JSON.parse(repaired);");
  lines.push("      const result = schema.safeParse(parsed);");
  lines.push("      if (result.success) return { success: true, data: result.data, raw, strategy: \"json_repair\", errors: [] };");
  lines.push("      errors.push(`json_repair: schema validation failed — ${formatZodError(result.error)}`);");
  lines.push("    } catch (e: any) {");
  lines.push("      errors.push(`json_repair: ${e.message}`);");
  lines.push("    }");
  lines.push("  }");
  lines.push("");
  lines.push("  // Strategy 5: Failure");
  lines.push("  return { success: false, data: null, raw, strategy: \"failed\", errors };");
  lines.push("}");
  lines.push("");

  // ─── Fence extraction ────────────────────────────────────────────────
  lines.push("/** Extract content from ```json ... ``` or ``` ... ``` fences */");
  lines.push("function extractJsonFence(raw: string): string | null {");
  lines.push("  // Try ```json first");
  lines.push("  const jsonFence = raw.match(/```(?:json|JSON)\\s*\\n([\\s\\S]*?)\\n```/);");
  lines.push("  if (jsonFence) return jsonFence[1].trim();");
  lines.push("  // Try bare fence");
  lines.push("  const bareFence = raw.match(/```\\s*\\n([\\s\\S]*?)\\n```/);");
  lines.push("  if (bareFence) return bareFence[1].trim();");
  lines.push("  // Try single-line fence");
  lines.push("  const singleFence = raw.match(/```([^`]+)```/);");
  lines.push("  if (singleFence) return singleFence[1].trim();");
  lines.push("  return null;");
  lines.push("}");
  lines.push("");

  // ─── Prose extraction ────────────────────────────────────────────────
  lines.push("/** Find the first JSON object or array in a string of prose */");
  lines.push("function extractJsonFromProse(raw: string): string | null {");
  lines.push("  // Find first { or [ that's likely the start of JSON");
  lines.push("  const objStart = raw.indexOf(\"{\");");
  lines.push("  const arrStart = raw.indexOf(\"[\");");
  lines.push("  const start = objStart >= 0 && arrStart >= 0 ? Math.min(objStart, arrStart) : Math.max(objStart, arrStart);");
  lines.push("  if (start < 0) return null;");
  lines.push("");
  lines.push("  const opening = raw[start];");
  lines.push("  const closing = opening === \"{\" ? \"}\" : \"]\";");
  lines.push("");
  lines.push("  // Walk forward counting braces to find the matching close");
  lines.push("  let depth = 0;");
  lines.push("  let inString = false;");
  lines.push("  let escape = false;");
  lines.push("  for (let i = start; i < raw.length; i++) {");
  lines.push("    const ch = raw[i];");
  lines.push("    if (escape) { escape = false; continue; }");
  lines.push("    if (ch === \"\\\\\") { escape = true; continue; }");
  lines.push("    if (ch === '\"') { inString = !inString; continue; }");
  lines.push("    if (inString) continue;");
  lines.push("    if (ch === \"{\" || ch === \"[\") depth++;");
  lines.push("    if (ch === \"}\" || ch === \"]\") {");
  lines.push("      depth--;");
  lines.push("      if (depth === 0) return raw.slice(start, i + 1);");
  lines.push("    }");
  lines.push("  }");
  lines.push("");
  lines.push("  // Truncated — try with closing brace appended");
  lines.push("  if (depth > 0) return raw.slice(start) + closing.repeat(depth);");
  lines.push("  return null;");
  lines.push("}");
  lines.push("");

  // ─── JSON repair ─────────────────────────────────────────────────────
  lines.push("/** Attempt to fix common LLM JSON mistakes */");
  lines.push("function repairJson(raw: string): string | null {");
  lines.push("  let s = raw.trim();");
  lines.push("");
  lines.push("  // Remove trailing comma before } or ]");
  lines.push("  s = s.replace(/,\\s*([}\\]])/g, \"$1\");");
  lines.push("");
  lines.push("  // Fix unquoted keys: {name: \"value\"} → {\"name\": \"value\"}");
  lines.push("  s = s.replace(/([{,]\\s*)([a-zA-Z_][a-zA-Z0-9_]*)\\s*:/g, '$1\"$2\":');");
  lines.push("");
  lines.push("  // Fix single-quoted strings: {'key': 'value'} → {\"key\": \"value\"}");
  lines.push("  s = s.replace(/'([^'\\\\]*(?:\\\\.[^'\\\\]*)*)'/g, '\"$1\"');");
  lines.push("");
  lines.push("  // Fix truncated JSON (unclosed braces/brackets)");
  lines.push("  let opens = 0;");
  lines.push("  let closes = 0;");
  lines.push("  let inStr = false;");
  lines.push("  let esc = false;");
  lines.push("  for (const ch of s) {");
  lines.push("    if (esc) { esc = false; continue; }");
  lines.push("    if (ch === \"\\\\\") { esc = true; continue; }");
  lines.push("    if (ch === '\"') { inStr = !inStr; continue; }");
  lines.push("    if (inStr) continue;");
  lines.push("    if (ch === \"{\" || ch === \"[\") opens++;");
  lines.push("    if (ch === \"}\" || ch === \"]\") closes++;");
  lines.push("  }");
  lines.push("  const unclosed = opens - closes;");
  lines.push("  if (unclosed > 0) {");
  lines.push("    // Guess closing chars based on what opened last");
  lines.push("    s += \"}\".repeat(unclosed);");
  lines.push("  }");
  lines.push("");
  lines.push("  // Verify it's valid now");
  lines.push("  try { JSON.parse(s); return s; } catch { return null; }");
  lines.push("}");
  lines.push("");

  // ─── Zod error formatting ────────────────────────────────────────────
  lines.push("/** Format Zod validation errors into a human-readable string */");
  lines.push("function formatZodError(error: z.ZodError): string {");
  lines.push("  return error.issues.map(i => `${i.path.join(\".\")}: ${i.message}`).join(\"; \");");
  lines.push("}");
  lines.push("");

  // ─── Largest fenced block (for string mode) ──────────────────────────
  lines.push("function extractLargestFencedBlock(raw: string): string {");
  lines.push("  const fenceRe = /```([a-zA-Z]*)\\s*\\n([\\s\\S]*?)\\n```/g;");
  lines.push("  const blocks: { lang: string; body: string }[] = [];");
  lines.push("  let m: RegExpExecArray | null;");
  lines.push("  while ((m = fenceRe.exec(raw)) !== null) {");
  lines.push("    blocks.push({ lang: (m[1] || \"\").toLowerCase(), body: m[2] });");
  lines.push("  }");
  lines.push("  if (blocks.length === 0) return raw;");
  lines.push("  // Prefer ts/typescript blocks, then largest");
  lines.push("  const tsBlocks = blocks.filter(b => [\"typescript\", \"ts\", \"tsx\", \"js\", \"javascript\"].includes(b.lang));");
  lines.push("  const pool = tsBlocks.length > 0 ? tsBlocks : blocks;");
  lines.push("  return pool.reduce((best, cur) => cur.body.length > best.body.length ? cur : best).body;");
  lines.push("}");
  lines.push("");

  // ─── Schema generators for each prompt's returns shape ────────────────
  lines.push("// ─── Prompt-specific schemas ──────────────────────────────────────");
  lines.push("");

  for (const p of jsonPrompts) {
    const schemaName = `${promptSchemaIdent(p.name)}Schema`;
    lines.push(`/** Schema for prompt: ${p.name} */`);
    if (p.output_type === "json" || p.output_type === "unknown" || p.output_type === "string") {
      lines.push(`export const ${schemaName} = z.record(z.unknown());`);
    } else {
      // For typed returns (list<File>, etc), accept any object
      lines.push(`export const ${schemaName} = z.unknown();`);
    }
    lines.push("");
  }

  // ─── Convenience: parse for a specific prompt ─────────────────────────
  lines.push("/** Parse output for a known prompt by name */");
  lines.push("export function parseForPrompt(promptName: string, raw: string): ParseResult<unknown> {");
  lines.push("  const schemas: Record<string, z.ZodType<unknown>> = {");
  for (const p of jsonPrompts) {
    lines.push(`    ${JSON.stringify(p.name)}: ${promptSchemaIdent(p.name)}Schema,`);
  }
  lines.push("  };");
  lines.push("  const schema = schemas[promptName] || z.unknown();");
  lines.push("  return parseStructuredOutput(raw, schema);");
  lines.push("}");

  return {
    path: "src/cognition/output_parser.ts",
    content: lines.join("\n"),
    language: "typescript",
    source_module: "cognition",
  };
}

function promptSchemaIdent(name: string): string {
  return name.replace(/[^a-zA-Z0-9]/g, "_");
}
