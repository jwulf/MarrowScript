/**
 * MarrowScript Budget Emitter (LLM Harness, Phase 3)
 *
 * Generates src/cognition/budget.ts. The budget tracker enforces per-trace
 * token / USD ceilings and exposes a tiny gauge surface that the existing
 * metrics layer (emit_maintenance.ts:emitMetrics) can read.
 *
 * Determinism: pure code generation, no Date.now() / Math.random() in the
 * emitted source.
 *
 * Integration:
 *   - The cognition prompt caller (emit_cognition.ts) calls `budget.assertCanSpend(...)`
 *     before the provider chat() and `budget.charge(...)` after the response,
 *     so a runaway prompt fails fast instead of burning the budget.
 *   - When `LLM_BUDGET_*` env vars are unset, the tracker is permissive
 *     (no-op). Setting either var enables enforcement.
 *   - On budget overrun, throws a typed `BudgetExceededError` whose `code`
 *     matches the failure rule emitted by emit_maintenance.ts (BUDGET_EXCEEDED).
 */

import * as IR from "./ir";
import { EmittedFile } from "./emitter";

export function emitBudget(system: IR.IRSystem): EmittedFile | null {
  const hasCognition =
    system.models.length > 0 ||
    system.prompts.length > 0 ||
    system.routers.length > 0;
  if (!hasCognition) return null;

  return {
    path: "src/cognition/budget.ts",
    content: emitBudgetSource(),
    language: "typescript",
    source_module: "cognition",
  };
}

function emitBudgetSource(): string {
  const lines: string[] = [];
  lines.push("// Generated by MarrowScript compiler. DO NOT EDIT.");
  lines.push("// Cognition Layer Phase 3 — per-trace budget tracker.");
  lines.push("//");
  lines.push("// Two ceilings, both opt-in:");
  lines.push("//   LLM_BUDGET_TOKENS_PER_TRACE  — absolute tokens (prompt + completion)");
  lines.push("//   LLM_BUDGET_USD_PER_TRACE     — fractional USD (cost class lookup table");
  lines.push("//                                   gives a pessimistic per-1k-tokens price)");
  lines.push("//");
  lines.push("// When neither is set, the tracker is permissive — it still records spend");
  lines.push("// for observability but never throws.");
  lines.push("");
  lines.push("import { counter, gauge } from \"../metrics\";");
  lines.push("");
  lines.push("/** Pessimistic per-1k-tokens USD floor by cost class. Used when models");
  lines.push(" * don't carry a cost-per-token annotation. Numbers are deliberately on the");
  lines.push(" * high side so the gauge never under-bills.");
  lines.push(" */");
  lines.push("const COST_FLOOR: Record<string, number> = {");
  lines.push("  tiny:   0.0001,");
  lines.push("  small:  0.0010,");
  lines.push("  medium: 0.0100,");
  lines.push("  large:  0.0300,");
  lines.push("};");
  lines.push("");
  lines.push("export class BudgetExceededError extends Error {");
  lines.push("  readonly code = \"BUDGET_EXCEEDED\";");
  lines.push("  constructor(");
  lines.push("    message: string,");
  lines.push("    readonly trace_id: string,");
  lines.push("    readonly kind: \"tokens\" | \"usd\",");
  lines.push("    readonly limit: number,");
  lines.push("    readonly observed: number,");
  lines.push("  ) {");
  lines.push("    super(message);");
  lines.push("    this.name = \"BudgetExceededError\";");
  lines.push("  }");
  lines.push("}");
  lines.push("");
  lines.push("export interface BudgetTracker {");
  lines.push("  readonly trace_id: string;");
  lines.push("  /** Cumulative tokens charged to this trace. */");
  lines.push("  readonly tokens: number;");
  lines.push("  /** Cumulative USD charged to this trace. */");
  lines.push("  readonly usd: number;");
  lines.push("  /** Throw if this trace cannot afford `tokens` more without exceeding the ceiling. */");
  lines.push("  assertCanSpend(tokens: number, costClass: string): void;");
  lines.push("  /** Record a completed call. Promotion `tokens=0` is allowed for cache hits. */");
  lines.push("  charge(tokens: number, costClass: string): void;");
  lines.push("  /** Refund a charge — used when a call was attempted and then rolled back (e.g. validation failed before billing). */");
  lines.push("  refund(tokens: number, costClass: string): void;");
  lines.push("}");
  lines.push("");
  // Read env once at module load. The values are inert if empty.
  lines.push("function readLimit(envName: string): number | null {");
  lines.push("  const raw = process.env[envName];");
  lines.push("  if (!raw) return null;");
  lines.push("  const v = Number(raw);");
  lines.push("  if (!Number.isFinite(v) || v <= 0) return null;");
  lines.push("  return v;");
  lines.push("}");
  lines.push("");
  lines.push("const TOKEN_LIMIT = readLimit(\"LLM_BUDGET_TOKENS_PER_TRACE\");");
  lines.push("const USD_LIMIT   = readLimit(\"LLM_BUDGET_USD_PER_TRACE\");");
  lines.push("");
  lines.push("class StandardBudget implements BudgetTracker {");
  lines.push("  readonly trace_id: string;");
  lines.push("  private _tokens = 0;");
  lines.push("  private _usd = 0;");
  lines.push("");
  lines.push("  constructor(trace_id: string) { this.trace_id = trace_id; }");
  lines.push("  get tokens(): number { return this._tokens; }");
  lines.push("  get usd(): number { return this._usd; }");
  lines.push("");
  lines.push("  private projectedUsd(addTokens: number, costClass: string): number {");
  lines.push("    const rate = COST_FLOOR[costClass] ?? COST_FLOOR.small;");
  lines.push("    return this._usd + (addTokens / 1000) * rate;");
  lines.push("  }");
  lines.push("");
  lines.push("  assertCanSpend(tokens: number, costClass: string): void {");
  lines.push("    if (TOKEN_LIMIT !== null && this._tokens + tokens > TOKEN_LIMIT) {");
  lines.push("      counter(\"cognition.budget_exceeded\", { kind: \"tokens\" });");
  lines.push("      throw new BudgetExceededError(");
  lines.push("        `Trace ${this.trace_id} would exceed token budget (${this._tokens + tokens} > ${TOKEN_LIMIT})`,");
  lines.push("        this.trace_id, \"tokens\", TOKEN_LIMIT, this._tokens + tokens,");
  lines.push("      );");
  lines.push("    }");
  lines.push("    if (USD_LIMIT !== null) {");
  lines.push("      const projected = this.projectedUsd(tokens, costClass);");
  lines.push("      if (projected > USD_LIMIT) {");
  lines.push("        counter(\"cognition.budget_exceeded\", { kind: \"usd\" });");
  lines.push("        throw new BudgetExceededError(");
  lines.push("          `Trace ${this.trace_id} would exceed USD budget ($${projected.toFixed(4)} > $${USD_LIMIT})`,");
  lines.push("          this.trace_id, \"usd\", USD_LIMIT, projected,");
  lines.push("        );");
  lines.push("      }");
  lines.push("    }");
  lines.push("  }");
  lines.push("");
  lines.push("  charge(tokens: number, costClass: string): void {");
  lines.push("    if (tokens <= 0) return;");
  lines.push("    this._tokens += tokens;");
  lines.push("    const rate = COST_FLOOR[costClass] ?? COST_FLOOR.small;");
  lines.push("    this._usd += (tokens / 1000) * rate;");
  lines.push("    counter(\"cognition.tokens_charged\", { cost_class: costClass });");
  lines.push("    gauge(\"cognition.trace_tokens\", this._tokens, { trace_id: this.trace_id });");
  lines.push("    gauge(\"cognition.trace_usd\", this._usd, { trace_id: this.trace_id });");
  lines.push("  }");
  lines.push("");
  lines.push("  refund(tokens: number, costClass: string): void {");
  lines.push("    if (tokens <= 0) return;");
  lines.push("    this._tokens = Math.max(0, this._tokens - tokens);");
  lines.push("    const rate = COST_FLOOR[costClass] ?? COST_FLOOR.small;");
  lines.push("    this._usd = Math.max(0, this._usd - (tokens / 1000) * rate);");
  lines.push("    counter(\"cognition.tokens_refunded\", { cost_class: costClass });");
  lines.push("  }");
  lines.push("}");
  lines.push("");
  lines.push("export function newBudget(trace_id: string): BudgetTracker {");
  lines.push("  return new StandardBudget(trace_id);");
  lines.push("}");
  lines.push("");
  lines.push("/** True if either ceiling is configured. Useful for callsite branching. */");
  lines.push("export function budgetEnforced(): boolean {");
  lines.push("  return TOKEN_LIMIT !== null || USD_LIMIT !== null;");
  lines.push("}");
  lines.push("");
  lines.push("/** Internal: expose the (immutable) limits for tests / observability. */");
  lines.push("export function budgetLimits(): { tokens: number | null; usd: number | null } {");
  lines.push("  return { tokens: TOKEN_LIMIT, usd: USD_LIMIT };");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}
