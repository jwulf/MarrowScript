/**
 * MarrowScript Memory Emitter (LLM Harness, Phase 4)
 *
 * Generates the graph-based semantic memory layer:
 *
 *   migrations/semantic_index.sql   — symbols + imports + calls + file_summaries
 *   src/memory/types.ts             — shared types
 *   src/memory/semantic_index.ts    — symbol extractor + index loader
 *   src/memory/retriever.ts         — bounded BFS over the graph
 *   src/memory/compressor.ts        — token-budgeted code-slice serializer
 *   src/memory/index.ts             — public entry: getIndex(), refreshIndex()
 *   bin/index_sources.ts            — script that runs the indexer at build time
 *
 * Contract (matches the cognition_catalog stub):
 *   index.walk(task: string, hopDepth: number, maxFiles: number)
 *     → { files: string[]; symbols: string[] }
 *
 * Determinism:
 *   - Sort everything by qualified id at every traversal step so BFS produces
 *     identical results for the same input.
 *   - The indexer hashes file contents and key tuples deterministically.
 *
 * Backends:
 *   - memory (default): in-process, suitable for tests and single-instance
 *     dev. The indexer populates an in-memory store on import.
 *   - pg: same data but persisted via migrations/semantic_index.sql, suitable
 *     for HA workers and shared indexes. Switched by LLM_MEMORY_BACKEND.
 *
 * The memory layer emits files only when at least one capability uses the
 * `semantic_slice` cognition primitive, OR the user opts in by setting any
 * `model` to provider:`http` and the harness wants graph-based retrieval. To
 * keep the rule simple, we emit when the system has prompts AND any
 * cognition primitive in {semantic_slice, compress_context} is referenced.
 */

import * as IR from "./ir";
import { EmittedFile } from "./emitter";

// ─── Public entry ────────────────────────────────────────────────────────────

/**
 * Decide whether memory files should be emitted. Two triggers:
 *   1. A capability uses `cognition: semantic_slice` or `cognition: compress_context`.
 *   2. The user explicitly opts in by declaring a memory primitive elsewhere
 *      (covered by trigger 1 since both primitives go through the catalog).
 */
export function memoryNeeded(system: IR.IRSystem): boolean {
  const memoryPrimitives = new Set(["semantic_slice", "compress_context"]);
  for (const mod of system.modules) {
    for (const iface of mod.interfaces) {
      for (const m of iface.methods) {
        if (m.cognition && memoryPrimitives.has(m.cognition.catalog_name)) return true;
      }
    }
  }
  // Phase 15: tool capabilities are not in the module tree but still pull
  // memory primitives in when they reference them.
  for (const t of system.tool_capabilities) {
    if (memoryPrimitives.has(t.cognition_primitive)) return true;
  }
  return false;
}

export function emitMemoryFiles(system: IR.IRSystem): EmittedFile[] {
  if (!memoryNeeded(system)) return [];

  return [
    {
      path: "migrations/semantic_index.sql",
      content: emitSemanticIndexSchema(),
      language: "sql",
      source_module: "memory",
    },
    {
      path: "src/memory/types.ts",
      content: emitMemoryTypes(),
      language: "typescript",
      source_module: "memory",
    },
    {
      path: "src/memory/semantic_index.ts",
      content: emitSemanticIndexRuntime(),
      language: "typescript",
      source_module: "memory",
    },
    {
      path: "src/memory/retriever.ts",
      content: emitRetriever(),
      language: "typescript",
      source_module: "memory",
    },
    {
      path: "src/memory/compressor.ts",
      content: emitCompressor(),
      language: "typescript",
      source_module: "memory",
    },
    {
      path: "src/memory/index.ts",
      content: emitMemoryIndexFile(),
      language: "typescript",
      source_module: "memory",
    },
    {
      path: "bin/index_sources.ts",
      content: emitIndexerScript(),
      language: "typescript",
      source_module: "memory",
    },
  ];
}

// ─── Postgres schema ─────────────────────────────────────────────────────────

function emitSemanticIndexSchema(): string {
  return `-- MarrowScript Memory Layer Phase 4
-- Generated by MarrowScript compiler. DO NOT EDIT.
--
-- Five tables that together form a small symbol-relationship graph:
--
--   symbols          one row per named declaration in the indexed corpus
--   imports          directed edge: importer file -> imported file
--   calls            directed edge: caller symbol -> callee symbol
--                    (best-effort — local resolution only)
--   file_summaries   per-file content hash, token count, optional summary
--   task_anchors     persisted seed lookups (task -> ranked symbol ids)
--                    so cold reads don't have to rebuild keyword scores
--
-- Indexes are tuned for the bounded BFS the retriever performs: lookups
-- are always (file, kind, name) or (from_file, to_file). Foreign keys are
-- omitted intentionally — a stale row beats a cascade-deletes-everything
-- migration. The indexer treats stale rows as cache invalidation hints.

CREATE TABLE IF NOT EXISTS symbols (
  id            VARCHAR(64) PRIMARY KEY,
  -- repo_id (Phase 10): tags every symbol with the repository it came from
  -- so per-repo filtering at retrieval time is cheap. Nullable + default '' so
  -- single-repo deployments don't have to set it; the indexer's --repo-id
  -- flag fills it in for multi-repo runs (forge_from_repos pipeline).
  repo_id       VARCHAR(64) NOT NULL DEFAULT '',
  file          VARCHAR     NOT NULL,
  name          VARCHAR     NOT NULL,
  kind          VARCHAR     NOT NULL,
  line          INT         NOT NULL,
  col           INT         NOT NULL DEFAULT 0,
  visibility    VARCHAR     NOT NULL DEFAULT 'internal',
  signature     TEXT,
  doc_excerpt   TEXT,
  content_hash  VARCHAR(64) NOT NULL,
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_symbols_file ON symbols (file, kind);
CREATE INDEX IF NOT EXISTS idx_symbols_name ON symbols (name);
CREATE INDEX IF NOT EXISTS idx_symbols_kind ON symbols (kind);
CREATE INDEX IF NOT EXISTS idx_symbols_repo ON symbols (repo_id);

CREATE TABLE IF NOT EXISTS imports (
  repo_id       VARCHAR(64) NOT NULL DEFAULT '',
  importer_file VARCHAR NOT NULL,
  imported_file VARCHAR NOT NULL,
  weight        INT     NOT NULL DEFAULT 1,
  PRIMARY KEY (repo_id, importer_file, imported_file)
);

CREATE INDEX IF NOT EXISTS idx_imports_imported ON imports (imported_file);
CREATE INDEX IF NOT EXISTS idx_imports_repo ON imports (repo_id);

CREATE TABLE IF NOT EXISTS calls (
  repo_id    VARCHAR(64) NOT NULL DEFAULT '',
  caller_id  VARCHAR(64) NOT NULL,
  callee_id  VARCHAR(64) NOT NULL,
  weight     INT         NOT NULL DEFAULT 1,
  PRIMARY KEY (repo_id, caller_id, callee_id)
);

CREATE INDEX IF NOT EXISTS idx_calls_callee ON calls (callee_id);
CREATE INDEX IF NOT EXISTS idx_calls_repo ON calls (repo_id);

CREATE TABLE IF NOT EXISTS file_summaries (
  repo_id       VARCHAR(64) NOT NULL DEFAULT '',
  file          VARCHAR     NOT NULL,
  content_hash  VARCHAR(64) NOT NULL,
  token_count   INT         NOT NULL,
  summary       TEXT,
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (repo_id, file)
);

CREATE TABLE IF NOT EXISTS task_anchors (
  task_hash    VARCHAR(64) PRIMARY KEY,
  task         TEXT        NOT NULL,
  symbol_ids   JSONB       NOT NULL,
  scored_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
`;
}

