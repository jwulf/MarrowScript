  lines.push("      });");
  lines.push("      counter(\"memory.index_built\");");
  lines.push("    }");
  lines.push("    return this.repo;");
  lines.push("  }");
  lines.push("");
  lines.push("  walk(task: string, hopDepth: number, maxFiles: number, repo_filter?: RepoFilter): SemanticSlice {");
  lines.push("    const r = this.ensure();");
