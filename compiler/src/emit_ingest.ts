  lines.push("  ensureWithinSandbox(dest, root);");
  lines.push("");
  lines.push("  const t0 = Date.now();");
  lines.push("  const alreadyCloned = fs.existsSync(path.join(dest, \".git\"));");
  lines.push("  if (opts.force && fs.existsSync(dest)) {");
  lines.push("    await fs.promises.rm(dest, { recursive: true, force: true });");
  lines.push("  }");
  lines.push("");
  lines.push("  if (!fs.existsSync(path.join(dest, \".git\"))) {");
  lines.push("    counter(\"cognition.ingest.clone\", { ref });");
  lines.push("    await gitCloneShallow(url, ref, dest, timeout_ms);");
  lines.push("  } else {");
  lines.push("    counter(\"cognition.ingest.cache_hit\", { ref });");
  lines.push("  }");
  lines.push("");
  lines.push("  // Account for size + file count after the clone — the --filter flag");
  lines.push("  // already drops blobs over 10MB, but we still need a hard ceiling on");
  lines.push("  // the total tree before the indexer touches it.");
  lines.push("  const acc = await walkAndCount(dest, root, max_files, max_bytes);");
  lines.push("  if (acc.oversize) {");
  lines.push("    throw new IngestError(\"oversize\", `Repo exceeds ${max_bytes} bytes (counted ${acc.total_bytes}+).`);");
  lines.push("  }");
  lines.push("  if (acc.too_many_files) {");
  lines.push("    throw new IngestError(\"too_many_files\", `Repo exceeds ${max_files} files (counted ${acc.file_count}+).`);");
  lines.push("  }");
  lines.push("");
  lines.push("  const head_sha = await gitHeadSha(dest);");
  lines.push("  const elapsed = Date.now() - t0;");
  lines.push("  histogram(\"cognition.ingest.latency_ms\", elapsed, { ref });");
  lines.push("");
  lines.push("  const report: IngestReport = {");
  lines.push("    local_path: dest,");
  lines.push("    head_sha,");
  lines.push("    file_count: acc.file_count,");
  lines.push("    total_bytes: acc.total_bytes,");
  lines.push("    url_redacted: redactUrl(url),");
