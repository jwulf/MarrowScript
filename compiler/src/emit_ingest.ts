/**
 * MarrowScript Ingest Emitter (LLM Harness, Phase 9 — repository ingestion)
 *
 * Generates a small read-only sandbox runtime at src/cognition/ingest.ts.
 *
 * Purpose:
 *   - Clone arbitrary public (or token-authenticated) Git repos into a
 *     bounded local cache.
 *   - Run safety checks BEFORE the indexer / compressor / generator looks at
 *     the cloned tree.
 *   - Produce a typed report `{ local_path, head_sha, file_count, total_bytes }`
 *     that downstream cognition primitives consume.
 *
 * Why this lives outside the catalog's inline emit():
 *   The catalog primitive `ingest_repository` (added in cognition_catalog.ts
 *   alongside this emitter) is the user-facing handle, but its
 *   implementation is non-trivial — git invocation, sandbox path resolution,
 *   deny-list enforcement, oversize-trip cancellation. Inlining all of that
 *   into the catalog spec's emit() string would be unreadable and hard to
 *   audit. Instead the catalog primitive calls into the helper module this
 *   emitter writes, which keeps the runtime module test-friendly and the
 *   catalog spec a one-liner.
 *
 * Determinism:
 *   - File contents are read deterministically; no Date.now() / Math.random()
 *     in the emitter source.
 *   - Sandbox sub-directory name is sha256(url + "|" + ref).slice(0, 16),
 *     so the same (url, ref) pair always lands in the same path. Re-running
 *     against the same commit short-circuits to a cache check.
 *
 * Safety:
 *   - URLs MUST pass the existing SSRF allowlist (the same one the
 *     openai_compat provider uses) — that opt-in moves into env so users
 *     who're paranoid can keep it locked to specific hosts (typically
 *     `https://github.com`). github.com is allowed by default.
 *   - Symlinks are followed only inside the sandbox; any symlink target
 *     escaping the sandbox root is rejected as `IngestError("escape")`.
 *   - Binary / archive / executable extensions are excluded from the file
 *     count and total-bytes checks have a hard ceiling (default 500MB).
 *   - File-count ceiling (default 50000) is enforced after the clone so
 *     monstrous monorepos fail loudly instead of OOMing the indexer.
 *   - The Git binary is invoked with execFile() (array args, not shell)
 *     and a per-clone timeout. No shell substitution, no command injection
 *     surface.
 *   - Tokens are never written to spans: the sandbox dir name is a
 *     content-addressed hash of (url, ref), not the URL itself, so a token
 *     embedded in a private-repo URL never escapes into trace storage. The
 *     audit logger gets the URL stripped of `x:TOKEN@` userinfo.
 */

import { EmittedFile } from "./emitter";

/**
 * Decide whether the ingest runtime needs to be emitted. Trigger: any
 * capability uses `cognition: ingest_repository`. Consistent with how
 * memoryNeeded() in emit_memory.ts decides on the semantic_slice runtime.
 */
import * as IR from "./ir";

export function ingestNeeded(system: IR.IRSystem): boolean {
  for (const mod of system.modules) {
    for (const iface of mod.interfaces) {
      for (const m of iface.methods) {
        if (m.cognition && m.cognition.catalog_name === "ingest_repository") return true;
      }
    }
  }
  return false;
}

export function emitIngestFiles(system: IR.IRSystem): EmittedFile[] {
  if (!ingestNeeded(system)) return [];

  return [
    {
      path: "src/cognition/ingest.ts",
      content: emitIngestRuntime(),
      language: "typescript",
      source_module: "cognition",
    },
  ];
}

