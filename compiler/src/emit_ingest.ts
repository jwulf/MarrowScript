  lines.push("      try {");
  lines.push("        const st = await fs.promises.stat(full);");
  lines.push("        size = st.size;");
  lines.push("      } catch {");
  lines.push("        continue;");
  lines.push("      }");
  lines.push("      file_count += 1;");
  lines.push("      total_bytes += size;");
  lines.push("      if (file_count > maxFiles) { too_many_files = true; break; }");
  lines.push("      if (total_bytes > maxBytes) { oversize = true; break; }");
  lines.push("    }");
  lines.push("    if (oversize || too_many_files) break;");
  lines.push("  }");
  lines.push("");
  lines.push("  return { file_count, total_bytes, oversize, too_many_files };");
