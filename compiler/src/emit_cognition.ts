/**
 * MarrowScript Cognition Emitter (LLM Harness, Phase 2)
 *
 * Compiles `model`, `prompt`, `router`, and `cognition:`-modified capabilities
 * from the IR into deterministic runtime modules under src/cognition/.
 *
 * Generated tree:
 *   src/cognition/router.ts        — deterministic decision tree per declared router
 *   src/cognition/prompts.ts       — typed callers, one async fn per prompt
 *   src/cognition/primitives.ts    — closed catalog of cognition primitives
 *   src/cognition/index.ts         — public entry point: registry + ctx builder
 *
 * Design notes:
 *   - Every prompt body is read from the existing extension_point mechanism
 *     (src/extensions.ts). Users author the prompt text once and it survives
 *     recompilation via the sentinel-bracketed regions.
 *   - Validation reuses the Zod schemas already generated by emit_zod.ts.
 *   - Retry / timeout / on_invalid actions are compiled in-line; the runtime
 *     never surprises the model with unbounded recursion.
 *   - Audit hooks call into src/logger and src/metrics — both already in the
 *     output tree thanks to emit_maintenance.ts.
 *
 * Determinism: deterministic ordering across IRPrompt[], IRRouter[],
 * IRCogModel[]. No Date.now() / Math.random() in emitted code.
 */

