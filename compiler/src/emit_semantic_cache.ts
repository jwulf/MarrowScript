/**
 * MarrowScript Semantic Cache (Phase 29)
 *
 * Upgrades the existing prompt cache from exact-hash matching to
 * similarity-aware matching. "Write a login page" and "Create an auth screen"
 * should cache-hit because they mean the same thing.
 *
 * Strategy (no embeddings required — local only):
 *   1. Normalize the input (lowercase, strip punctuation, sort words)
 *   2. Generate trigram set from normalized input
 *   3. Compare trigram overlap (Jaccard similarity) against cached entries
 *   4. If similarity > threshold (default 0.7), return cached result
 *   5. Otherwise, call the model and cache the result
 *
 * Why trigrams and not embeddings:
 *   - Zero dependencies (no embedding model needed)
 *   - Sub-millisecond lookup (string operations, not vector math)
 *   - Deterministic (same input always computes same trigrams)
 *   - Good enough for the common case (paraphrased prompts)
 *
 * Emits: src/cognition/semantic_cache.ts
 */

import * as IR from "./ir";
import { EmittedFile } from "./emitter";

export function emitSemanticCache(system: IR.IRSystem): EmittedFile | null {
  // Only emit if there are prompts with cache: configured
  const cachedPrompts = system.prompts.filter(p => p.cache !== null);
  if (cachedPrompts.length === 0) return null;

  const lines: string[] = [];
  lines.push("// Generated by MarrowScript compiler. DO NOT EDIT.");
  lines.push("// Semantic Cache (Phase 29) — similarity-aware prompt caching.");
  lines.push("//");
  lines.push("// Falls back to exact hash when similarity is below threshold.");
  lines.push("// Zero external dependencies — trigram-based, sub-millisecond.");
  lines.push("");
  lines.push("import { createHash } from \"crypto\";");
  lines.push("");

  // ─── Types ───────────────────────────────────────────────────────────
  lines.push("export interface CacheEntry<T> {");
  lines.push("  key: string;");
  lines.push("  normalized: string;");
  lines.push("  trigrams: Set<string>;");
  lines.push("  value: T;");
  lines.push("  created_at: number;");
  lines.push("  ttl_ms: number;");
  lines.push("  hits: number;");
  lines.push("}");
  lines.push("");
  lines.push("export interface SemanticCacheOptions {");
  lines.push("  /** Similarity threshold (0-1). Default: 0.7 */");
  lines.push("  threshold?: number;");
  lines.push("  /** Max entries in cache. Default: 500 */");
  lines.push("  maxEntries?: number;");
  lines.push("  /** Default TTL in ms. Default: 1 hour */");
  lines.push("  ttl_ms?: number;");
  lines.push("}");
  lines.push("");

  // ─── Core class ──────────────────────────────────────────────────────
  lines.push("export class SemanticCache<T = unknown> {");
  lines.push("  private entries: CacheEntry<T>[] = [];");
  lines.push("  private threshold: number;");
  lines.push("  private maxEntries: number;");
  lines.push("  private defaultTtl: number;");
  lines.push("");
  lines.push("  constructor(options: SemanticCacheOptions = {}) {");
  lines.push("    this.threshold = options.threshold ?? 0.7;");
  lines.push("    this.maxEntries = options.maxEntries ?? 500;");
  lines.push("    this.defaultTtl = options.ttl_ms ?? 3_600_000;");
  lines.push("  }");
  lines.push("");
  lines.push("  /**");
  lines.push("   * Look up a cached result by semantic similarity.");
  lines.push("   * Returns the cached value if similarity > threshold, otherwise null.");
  lines.push("   */");
  lines.push("  get(input: string): { value: T; similarity: number; key: string } | null {");
  lines.push("    const now = Date.now();");
  lines.push("    const normalized = normalize(input);");
  lines.push("    const inputTrigrams = trigrams(normalized);");
  lines.push("");
  lines.push("    // Exact hash match first (fastest path)");
  lines.push("    const exactKey = hashKey(input);");
  lines.push("    const exact = this.entries.find(e => e.key === exactKey && now - e.created_at < e.ttl_ms);");
  lines.push("    if (exact) { exact.hits++; return { value: exact.value, similarity: 1.0, key: exact.key }; }");
  lines.push("");
  lines.push("    // Semantic similarity search");
  lines.push("    let bestMatch: CacheEntry<T> | null = null;");
  lines.push("    let bestSimilarity = 0;");
  lines.push("");
  lines.push("    for (const entry of this.entries) {");
  lines.push("      if (now - entry.created_at >= entry.ttl_ms) continue; // expired");
  lines.push("      const sim = jaccardSimilarity(inputTrigrams, entry.trigrams);");
  lines.push("      if (sim > bestSimilarity && sim >= this.threshold) {");
  lines.push("        bestSimilarity = sim;");
  lines.push("        bestMatch = entry;");
  lines.push("      }");
  lines.push("    }");
  lines.push("");
  lines.push("    if (bestMatch) {");
  lines.push("      bestMatch.hits++;");
  lines.push("      return { value: bestMatch.value, similarity: bestSimilarity, key: bestMatch.key };");
  lines.push("    }");
  lines.push("");
  lines.push("    return null;");
  lines.push("  }");
  lines.push("");
  lines.push("  /**");
  lines.push("   * Store a result in the cache.");
  lines.push("   */");
  lines.push("  set(input: string, value: T, ttl_ms?: number): void {");
  lines.push("    const normalized = normalize(input);");
  lines.push("    const entry: CacheEntry<T> = {");
  lines.push("      key: hashKey(input),");
  lines.push("      normalized,");
  lines.push("      trigrams: trigrams(normalized),");
  lines.push("      value,");
  lines.push("      created_at: Date.now(),");
  lines.push("      ttl_ms: ttl_ms ?? this.defaultTtl,");
  lines.push("      hits: 0,");
  lines.push("    };");
  lines.push("");
  lines.push("    // Evict expired + LRU if at capacity");
  lines.push("    const now = Date.now();");
  lines.push("    this.entries = this.entries.filter(e => now - e.created_at < e.ttl_ms);");
  lines.push("    if (this.entries.length >= this.maxEntries) {");
  lines.push("      // Remove least-hit entry");
  lines.push("      this.entries.sort((a, b) => a.hits - b.hits);");
  lines.push("      this.entries.shift();");
  lines.push("    }");
  lines.push("");
  lines.push("    this.entries.push(entry);");
  lines.push("  }");
  lines.push("");
  lines.push("  /** Get cache stats */");
  lines.push("  stats(): { entries: number; total_hits: number; hit_rate: string } {");
  lines.push("    const totalHits = this.entries.reduce((s, e) => s + e.hits, 0);");
  lines.push("    return { entries: this.entries.length, total_hits: totalHits, hit_rate: \"N/A\" };");
  lines.push("  }");
  lines.push("");
  lines.push("  /** Clear all entries */");
  lines.push("  clear(): void { this.entries = []; }");
  lines.push("}");
  lines.push("");

  // ─── Utility functions ───────────────────────────────────────────────
  lines.push("/** Normalize input: lowercase, strip punctuation, collapse whitespace */");
  lines.push("function normalize(input: string): string {");
  lines.push("  return input.toLowerCase().replace(/[^a-z0-9\\s]/g, \" \").replace(/\\s+/g, \" \").trim();");
  lines.push("}");
  lines.push("");
  lines.push("/** Generate character trigrams from a string */");
  lines.push("function trigrams(s: string): Set<string> {");
  lines.push("  const set = new Set<string>();");
  lines.push("  for (let i = 0; i <= s.length - 3; i++) {");
  lines.push("    set.add(s.slice(i, i + 3));");
  lines.push("  }");
  lines.push("  return set;");
  lines.push("}");
  lines.push("");
  lines.push("/** Jaccard similarity between two sets */");
  lines.push("function jaccardSimilarity(a: Set<string>, b: Set<string>): number {");
  lines.push("  if (a.size === 0 && b.size === 0) return 1;");
  lines.push("  let intersection = 0;");
  lines.push("  for (const item of a) { if (b.has(item)) intersection++; }");
  lines.push("  const union = a.size + b.size - intersection;");
  lines.push("  return union > 0 ? intersection / union : 0;");
  lines.push("}");
  lines.push("");
  lines.push("/** Hash a string to a cache key */");
  lines.push("function hashKey(input: string): string {");
  lines.push("  return createHash(\"sha256\").update(input).digest(\"hex\").slice(0, 16);");
  lines.push("}");
  lines.push("");

  // ─── Singleton per prompt ────────────────────────────────────────────
  lines.push("/** Per-prompt cache instances */");
  lines.push("const CACHES: Record<string, SemanticCache> = {};");
  lines.push("");
  lines.push("export function getPromptCache(promptName: string, options?: SemanticCacheOptions): SemanticCache {");
  lines.push("  if (!CACHES[promptName]) CACHES[promptName] = new SemanticCache(options);");
  lines.push("  return CACHES[promptName];");
  lines.push("}");

  return {
    path: "src/cognition/semantic_cache.ts",
    content: lines.join("\n"),
    language: "typescript",
    source_module: "cognition",
  };
}
