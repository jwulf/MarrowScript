/**
 * MarrowScript Repair Emitter (LLM Harness, Phase 5)
 *
 * Generates src/cognition/repair.ts. One repair function is emitted per
 * prompt that declares `on_invalid: retry_with_repair_prompt`.
 *
 * Each repair function:
 *   1. Takes the original input + the failing output + the issues list
 *   2. Builds a compact "fix this" prompt — explicitly smaller in scope
 *      than the original (no surrounding context, just the diff target)
 *   3. Sends a single-shot call to the same model
 *   4. Returns the repaired value, or throws if the repair itself fails
 *
 * Design rule: repair attempts are always bounded and always smaller than the
 * original prompt. The runtime never recurses — repair is single-shot. This
 * matches the plan's "retries should become smaller, simpler, more constrained
 * over time" guidance.
 *
 * Determinism: the repair-prompt template is content-addressed and stable.
 * Given the same input + output + issues, the assembled message is identical.
 */

import * as IR from "./ir";
import { EmittedFile } from "./emitter";

/**
 * Repair files only emit when at least one prompt has
 * `on_invalid: retry_with_repair_prompt`. Other systems get nothing.
 */
export function repairNeeded(system: IR.IRSystem): boolean {
  return system.prompts.some(p => p.on_invalid === "retry_with_repair_prompt");
}

export function emitRepairFile(system: IR.IRSystem): EmittedFile | null {
  if (!repairNeeded(system)) return null;
  return {
    path: "src/cognition/repair.ts",
    content: emitRepairRuntime(system),
    language: "typescript",
    source_module: "cognition",
  };
}

function emitRepairRuntime(system: IR.IRSystem): string {
  const lines: string[] = [];
  lines.push("// Generated by MarrowScript compiler. DO NOT EDIT.");
  lines.push("// Cognition Layer Phase 5 — repair prompts.");
  lines.push("//");
  lines.push("// One repair function per prompt that declares `on_invalid: retry_with_repair_prompt`.");
  lines.push("// Repair calls are single-shot (max_attempts: 1) and use a smaller, more");
  lines.push("// constrained message than the original prompt — exactly what the plan");
  lines.push("// asks for: 'retries should become smaller, simpler, more constrained.'");
  lines.push("");
  lines.push("import { logger } from \"../logger\";");
  lines.push("import { counter } from \"../metrics\";");
  lines.push("import { getModel, type ModelEntry } from \"../providers\";");
  lines.push("");
  lines.push("export interface RepairContext {");
  lines.push("  trace_id: string;");
  lines.push("  signal?: AbortSignal;");
  lines.push("}");
  lines.push("");
  lines.push("export interface RepairResult<T> {");
  lines.push("  ok: boolean;");
  lines.push("  value: T | null;");
  lines.push("  /** Best-effort tokens used by the repair call (for budget accounting). */");
  lines.push("  tokens_used: number;");
  lines.push("}");
  lines.push("");
  // Helper: build a uniformly-shaped repair message. Keeping the format
  // identical across prompts means the model sees a familiar structure
  // regardless of which prompt is being repaired.
  lines.push("function buildRepairMessage(opts: {");
  lines.push("  prompt_name: string;");
  lines.push("  original_input: Record<string, unknown>;");
  lines.push("  bad_output: unknown;");
  lines.push("  issues: string[];");
  lines.push("  output_type: string;");
  lines.push("}): string {");
  lines.push("  const inputJson = JSON.stringify(opts.original_input, null, 2).slice(0, 1500);");
  lines.push("  const badJson = typeof opts.bad_output === \"string\"");
  lines.push("    ? opts.bad_output.slice(0, 1500)");
  lines.push("    : JSON.stringify(opts.bad_output, null, 2).slice(0, 1500);");
  lines.push("  const issuesList = opts.issues.length > 0");
  lines.push("    ? opts.issues.slice(0, 5).map((i, n) => `${n + 1}. ${String(i).slice(0, 200)}`).join(\"\\n\")");
  lines.push("    : \"output failed validation (no specific issues reported)\";");
  lines.push("  // Match common failure patterns and append targeted guidance the");
  lines.push("  // model can act on. Generic 'fix it' prompts have a much lower");
  lines.push("  // success rate than 'fix it; here's specifically what went wrong'.");
  lines.push("  const guidance: string[] = [];");
  lines.push("  const issuesText = opts.issues.join(\" \");");
  lines.push("  if (/Unterminated template literal/i.test(issuesText)) {");
  lines.push("    guidance.push(");
  lines.push("      \"Specific guidance: an unterminated template literal means a backtick \" +");
  lines.push("      \"(`) somewhere in your file isn't matched. The most common cause is \" +");
  lines.push("      \"emitting a TypeScript template literal that contains markdown code \" +");
  lines.push("      \"fences (which use backticks). Rewrite the file to NOT use backtick \" +");
  lines.push("      \"strings at all. Use single-quoted strings, double-quoted strings, \" +");
  lines.push("      \"or arrays of strings joined with '\\\\n'. If you need string \" +");
  lines.push("      \"interpolation, use the '+' operator. This avoids the problem entirely.\"");
  lines.push("    );");
  lines.push("  }");
  lines.push("  if (/Cannot find module/i.test(issuesText)) {");
  lines.push("    guidance.push(");
  lines.push("      \"Specific guidance: one or more imports reference a package that \" +");
  lines.push("      \"doesn't exist. Either swap to a real package name (verify it actually \" +");
  lines.push("      \"exists on npm) or drop the import and reimplement using only Node.js \" +");
  lines.push("      \"builtins (fs, path, crypto, child_process, http, https, os, url, \" +");
  lines.push("      \"events, stream).\"");
  lines.push("    );");
  lines.push("  }");
  lines.push("  if (/Cannot find name/i.test(issuesText)) {");
  lines.push("    guidance.push(");
  lines.push("      \"Specific guidance: you referenced a type or value that's never \" +");
  lines.push("      \"declared. Add a real `interface` or `type` declaration for any type \" +");
  lines.push("      \"you reference. JSDoc-only types do NOT count — they must be real TS \" +");
  lines.push("      \"declarations.\"");
  lines.push("    );");
  lines.push("  }");
  lines.push("  return [");
  lines.push("    \"You produced an output that failed validation. Fix it. Reply ONLY with the corrected output.\",");
  lines.push("    `Expected output type: ${opts.output_type}`,");
  lines.push("    \"\",");
  lines.push("    \"Original input:\",");
  lines.push("    inputJson,");
  lines.push("    \"\",");
  lines.push("    \"Your previous output:\",");
  lines.push("    badJson,");
  lines.push("    \"\",");
  lines.push("    \"Validation issues:\",");
  lines.push("    issuesList,");
  lines.push("    ...(guidance.length > 0 ? [\"\", ...guidance] : []),");
  lines.push("  ].join(\"\\n\");");
  lines.push("}");
  lines.push("");
  // Generate one repair function per qualifying prompt.
  const sortedPrompts = [...system.prompts]
    .filter(p => p.on_invalid === "retry_with_repair_prompt")
    .sort((a, b) => a.name.localeCompare(b.name));

  for (const p of sortedPrompts) {
    const ident = p.name.replace(/[^a-zA-Z0-9_]/g, "_");
    // The repair function uses the SAME model the original prompt was bound
    // to, even when the prompt routes via a router. (Repair is not a routing
    // decision — it's a "fix what you just said" decision.) When a prompt
    // routes through a router, we use the fallback model if declared; the
    // first tier otherwise.
    let modelLookup: string;
    if (p.model_ref) {
      modelLookup = `getModel(${JSON.stringify(p.model_ref)})`;
    } else if (p.router_ref) {
      // Find the first tier of the router for repair fallback.
      const router = system.routers.find(r => r.name === p.router_ref);
      const fallbackModel = router?.fallback_model_ref
        ?? router?.tiers[0]?.model_ref
        ?? "";
      modelLookup = fallbackModel
        ? `getModel(${JSON.stringify(fallbackModel)})`
        : `null as unknown as ModelEntry`;
    } else {
      modelLookup = `null as unknown as ModelEntry`;
    }
    lines.push(`/** Repair: fix a previously-rejected output of prompt '${p.name}'. */`);
    lines.push(`export async function repair_${ident}(args: {`);
    lines.push(`  original_input: Record<string, unknown>;`);
    lines.push(`  bad_output: unknown;`);
    lines.push(`  issues: string[];`);
    lines.push(`}, ctx: RepairContext): Promise<RepairResult<unknown>> {`);
    lines.push(`  const __model: ModelEntry = ${modelLookup};`);
    lines.push(`  if (!__model) {`);
    lines.push(`    logger.warn("cognition_repair_no_model", { event: "repair.${p.name}", status: "rejected", trace_id: ctx.trace_id });`);
    lines.push(`    return { ok: false, value: null, tokens_used: 0 };`);
    lines.push(`  }`);
    lines.push(`  const __message = buildRepairMessage({`);
    lines.push(`    prompt_name: ${JSON.stringify(p.name)},`);
    lines.push(`    original_input: args.original_input,`);
    lines.push(`    bad_output: args.bad_output,`);
    lines.push(`    issues: args.issues,`);
    lines.push(`    output_type: ${JSON.stringify(p.output_type)},`);
    lines.push(`  });`);
    lines.push(`  // Single-shot — a repair that itself fails should bubble; recursing on`);
    lines.push(`  // a repair would defeat the bounded-recursion guarantee.`);
    lines.push(`  // Timeout matches the parent prompt's timeout: a repair is the same`);
    lines.push(`  // network shape, so the network ceiling shouldn't shrink. (Earlier`);
    lines.push(`  // versions used parent/2 which was too aggressive for slow free-tier`);
    lines.push(`  // providers like OpenRouter on heavy prompts.)`);
    lines.push(`  const __controller = new AbortController();`);
    lines.push(`  const __timer = setTimeout(() => __controller.abort(), Math.max(5000, ${p.timeout_ms}));`);
    lines.push(`  if (ctx.signal) ctx.signal.addEventListener("abort", () => __controller.abort());`);
    lines.push(`  try {`);
    lines.push(`    counter("cognition.repair.attempted", { prompt: ${JSON.stringify(p.name)} });`);
    lines.push(`    const __resp = await __model.provider.chat({`);
    lines.push(`      model: __model.modelName,`);
    lines.push(`      messages: [{ role: "user", content: __message }],`);
    lines.push(`      temperature: 0,                       // deterministic repair`);
    lines.push(`      max_output: Math.floor(__model.maxOutput / 2),  // smaller than original`);
    lines.push(`      stop: __model.stop,`);
    lines.push(`    }, __controller.signal);`);
    lines.push(`    clearTimeout(__timer);`);
    lines.push(`    const tokens_used = (__resp.usage.prompt_tokens || 0) + (__resp.usage.completion_tokens || 0);`);
    lines.push(`    counter("cognition.repair.completed", { prompt: ${JSON.stringify(p.name)} });`);
    lines.push(`    logger.info("cognition_repair_ok", {`);
    lines.push(`      event: "repair.${p.name}",`);
    lines.push(`      status: "success",`);
    lines.push(`      trace_id: ctx.trace_id,`);
    lines.push(`      metadata: { tokens_used }`);
    lines.push(`    });`);
    lines.push(`    return { ok: true, value: __resp.content, tokens_used };`);
    lines.push(`  } catch (__err) {`);
    lines.push(`    clearTimeout(__timer);`);
    lines.push(`    counter("cognition.repair.failed", { prompt: ${JSON.stringify(p.name)} });`);
    lines.push(`    const msg = __err instanceof Error ? __err.message : String(__err);`);
    lines.push(`    logger.error("cognition_repair_failed", {`);
    lines.push(`      event: "repair.${p.name}",`);
    lines.push(`      status: "failure",`);
    lines.push(`      trace_id: ctx.trace_id,`);
    lines.push(`      metadata: { error: msg.slice(0, 256) }`);
    lines.push(`    });`);
    lines.push(`    return { ok: false, value: null, tokens_used: 0 };`);
    lines.push(`  }`);
    lines.push(`}`);
    lines.push("");
  }

  // Dispatch table — let the prompt body call repair by name.
  lines.push("export const REPAIRS: Record<string, (args: { original_input: Record<string, unknown>; bad_output: unknown; issues: string[] }, ctx: RepairContext) => Promise<RepairResult<unknown>>> = {");
  for (const p of sortedPrompts) {
    const ident = p.name.replace(/[^a-zA-Z0-9_]/g, "_");
    lines.push(`  ${JSON.stringify(p.name)}: repair_${ident},`);
  }
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}
