/**
 * MarrowScript Evaluation Emitter (LLM Harness, Phase 16)
 *
 * Generates one runner file per `evaluation` declaration, plus an index and
 * a thin CLI entry. The emitted layout:
 *
 *   eval/<name>.ts          — typed case runner for one evaluation
 *   eval/index.ts           — registry mapping name → runner
 *   bin/evaluate.ts         — CLI: `npx ts-node bin/evaluate.ts <name?>`
 *
 * Each runner:
 *   - imports the prompt by name from the cognition layer
 *   - executes every case via callPrompt
 *   - runs each declared expectation against the parsed output
 *   - aggregates a per-case pass/fail + an overall pass_rate
 *   - compares against the baseline floor and exits non-zero on regression
 *   - writes eval/<name>.last.json so subsequent runs can compute deltas
 *
 * Why this shape:
 *   - One runner per evaluation keeps individual evals fast (no need to
 *     load every other eval's case fixtures).
 *   - The registry lets the CLI pick by name, OR run --all in a stable order.
 *   - Baselines live as on-disk JSON (eval/<name>.last.json) so a fresh
 *     checkout can establish them. CI just commits the JSON file alongside
 *     the spec.
 *
 * Determinism: cases are emitted in declaration order; expectation order
 * is preserved; no Date.now()/Math.random() in the emitter itself.
 */

import * as IR from "./ir";
import { EmittedFile } from "./emitter";

export function evaluationsNeeded(system: IR.IRSystem): boolean {
  return Array.isArray(system.evaluations) && system.evaluations.length > 0;
}

export function emitEvaluationFiles(system: IR.IRSystem): EmittedFile[] {
  if (!evaluationsNeeded(system)) return [];
  const files: EmittedFile[] = [];

  // One runner per evaluation. Sorted by name for stable file ordering on
  // disk; each runner is otherwise self-contained.
  const sorted = [...system.evaluations].sort((a, b) => a.name.localeCompare(b.name));
  for (const ev of sorted) {
    files.push({
      path: `eval/${ev.name}.ts`,
      content: emitRunner(ev),
      language: "typescript",
      source_module: "eval",
    });
  }

  // Index — maps name → runner so the CLI doesn't have to know paths.
  files.push({
    path: "eval/index.ts",
    content: emitIndex(sorted),
    language: "typescript",
    source_module: "eval",
  });

  // CLI entry — `npx ts-node bin/evaluate.ts <name?>` runs one eval (or all).
  files.push({
    path: "bin/evaluate.ts",
    content: emitCLI(sorted),
    language: "typescript",
    source_module: "eval",
  });

  return files;
}

// ─── Runner per evaluation ──────────────────────────────────────────────────

function emitRunner(ev: IR.IREvaluation): string {
  const lines: string[] = [];
  lines.push("// Generated by MarrowScript compiler. DO NOT EDIT.");
  lines.push(`// Phase 16 — evaluation runner for '${ev.name}'.`);
  lines.push("//");
  lines.push(`// Targets prompt: ${ev.prompt_ref}`);
  lines.push(`// Cases: ${ev.cases.length}, baseline pass_rate floor: ${ev.min_pass_rate}`);
  lines.push("//");
  lines.push("// Run via: npx ts-node bin/evaluate.ts " + ev.name);
  lines.push("");
  lines.push("import { callPrompt } from \"../src/cognition\";");
  lines.push("import * as fs from \"fs\";");
  lines.push("import * as path from \"path\";");
  lines.push("");
  // ── Case fixtures table. Inputs are emitted as TypeScript literals so
  // the runner has zero parse overhead per case.
  lines.push("interface CaseInput { [k: string]: unknown; }");
  lines.push("interface ExpectationResult { name: string; ok: boolean; reason?: string; }");
  lines.push("interface CaseResult {");
  lines.push("  case: string;");
  lines.push("  pass: boolean;");
  lines.push("  expectations: ExpectationResult[];");
  lines.push("  duration_ms: number;");
  lines.push("  error?: string;");
  lines.push("}");
  lines.push("");
  lines.push("const CASES: { name: string; input: CaseInput }[] = [");
  for (const c of ev.cases) {
    lines.push("  {");
    lines.push(`    name: ${JSON.stringify(c.name)},`);
    lines.push("    input: {");
    for (const b of c.input) {
      // Phase 16 emits literal expressions verbatim. The lowering already
      // produced TypeScript-shaped output for primitive literals (strings
      // are quoted, numbers/booleans bare). For expressions that aren't
      // pure literals we fall through to a JSON.parse-safe form.
      lines.push(`      ${b.param}: ${b.value},`);
    }
    lines.push("    },");
    lines.push("  },");
  }
  lines.push("];");
  lines.push("");

  // ── Expectation runners. Each operator is dispatched in line so the
  // runner has no indirection at call time.
  lines.push("function checkExpectations(output: unknown, durationMs: number): ExpectationResult[] {");
  lines.push("  const results: ExpectationResult[] = [];");
  lines.push("  // Coerce output to the most useful string form for code-shape ops:");
  lines.push("  // a string output IS the body; a File-shaped output uses .content;");
  lines.push("  // a list<File> output joins all .content for shape-level checks.");
  lines.push("  const asString = ((): string => {");
  lines.push("    if (typeof output === \"string\") return output;");
  lines.push("    if (output && typeof output === \"object\" && \"content\" in (output as object)) {");
  lines.push("      const c = (output as { content?: unknown }).content;");
  lines.push("      return typeof c === \"string\" ? c : \"\";");
  lines.push("    }");
  lines.push("    if (Array.isArray(output)) {");
  lines.push("      return output.map(f => (f && typeof f === \"object\" && typeof (f as { content?: unknown }).content === \"string\")");
  lines.push("        ? (f as { content: string }).content : \"\").join(\"\\n\");");
  lines.push("    }");
  lines.push("    try { return JSON.stringify(output); } catch { return String(output); }");
  lines.push("  })();");
  lines.push("");

  // Iterate over each declared expectation, emitting an inline check.
  // We attach one ExpectationResult per check so the failure report can
  // pinpoint which assertion broke.
  for (let i = 0; i < ev.cases.length; i++) {
    // expectations are per-case; we'll dispatch them in run() below.
  }

  // We can't generate expectation logic per case here — they apply per
  // case. Instead, the function receives a list of expectations from the
  // caller. So this helper is per-call. Move logic into run() loop.
  lines.push("  return results;");
  lines.push("}");
  lines.push("");

  // ── Main run() function. Walks cases, calls the prompt, runs the case's
  // expectations, aggregates results.
  lines.push("export interface EvaluationRunResult {");
  lines.push("  evaluation: string;");
  lines.push("  prompt: string;");
  lines.push("  total: number;");
  lines.push("  passed: number;");
  lines.push("  pass_rate: number;");
  lines.push("  baseline_pass_rate: number;");
  lines.push("  baseline_ok: boolean;");
  lines.push("  cases: CaseResult[];");
  lines.push("  finished_at: string;");
  lines.push("}");
  lines.push("");
  lines.push("export async function run(): Promise<EvaluationRunResult> {");
  lines.push(`  const evaluation = ${JSON.stringify(ev.name)};`);
  lines.push(`  const prompt = ${JSON.stringify(ev.prompt_ref)};`);
  lines.push(`  const baseline = ${ev.min_pass_rate};`);
  lines.push("  const cases: CaseResult[] = [];");
  lines.push("  for (let i = 0; i < CASES.length; i++) {");
  lines.push("    const c = CASES[i];");
  lines.push("    const start = Date.now();");
  lines.push("    let output: unknown = null;");
  lines.push("    let error: string | undefined = undefined;");
  lines.push("    try {");
  lines.push("      output = await callPrompt(prompt, c.input);");
  lines.push("    } catch (e) {");
  lines.push("      error = e instanceof Error ? e.message : String(e);");
  lines.push("    }");
  lines.push("    const duration_ms = Date.now() - start;");
  lines.push("    const expectations: ExpectationResult[] = [];");
  // Per-case dispatch: emit one branch per case index.
  for (let i = 0; i < ev.cases.length; i++) {
    lines.push(`    if (i === ${i}) {`);
    for (const exp of ev.cases[i].expectations) {
      emitExpectationCheck(exp, lines, "      ");
    }
    lines.push("    }");
  }
  lines.push("    const pass = !error && expectations.every(e => e.ok);");
  lines.push("    cases.push({ case: c.name, pass, expectations, duration_ms, error });");
  lines.push("  }");
  lines.push("  const passed = cases.filter(c => c.pass).length;");
  lines.push("  const total = cases.length;");
  lines.push("  const pass_rate = total === 0 ? 0 : passed / total;");
  lines.push("  const baseline_ok = pass_rate >= baseline;");
  lines.push("  const result: EvaluationRunResult = {");
  lines.push("    evaluation,");
  lines.push("    prompt,");
  lines.push("    total,");
  lines.push("    passed,");
  lines.push("    pass_rate,");
  lines.push("    baseline_pass_rate: baseline,");
  lines.push("    baseline_ok,");
  lines.push("    cases,");
  lines.push("    finished_at: new Date().toISOString(),");
  lines.push("  };");
  lines.push("  // Persist the run so subsequent runs can compute deltas. The");
  lines.push("  // .last.json file is the de-facto baseline; `git diff eval/` shows");
  lines.push("  // the regression at PR review time.");
  lines.push("  try {");
  lines.push("    const dir = path.join(process.cwd(), \"eval\");");
  lines.push("    if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });");
  lines.push(`    fs.writeFileSync(path.join(dir, ${JSON.stringify(ev.name + ".last.json")}), JSON.stringify(result, null, 2));`);
  lines.push("  } catch { /* non-fatal */ }");
  lines.push("  return result;");
  lines.push("}");
  lines.push("");
  // Allow direct execution for ad-hoc runs.
  lines.push("if (require.main === module) {");
  lines.push("  run().then(r => {");
  lines.push("    console.log(JSON.stringify(r, null, 2));");
  lines.push("    if (!r.baseline_ok) process.exit(1);");
  lines.push("  }).catch(err => {");
  lines.push("    console.error(\"evaluation runner failed:\", err);");
  lines.push("    process.exit(2);");
  lines.push("  });");
  lines.push("}");
  return lines.join("\n");
}

/**
 * Emit one inline expectation check. Each kind appends a single
 * ExpectationResult to the local `expectations` array. Keeping the dispatch
 * inline (rather than a registered function table) means the runner has no
 * runtime dependencies beyond the cognition layer + node stdlib.
 */
function emitExpectationCheck(exp: IR.IREvaluationExpectation, lines: string[], indent: string): void {
  switch (exp.kind) {
    case "passes":
      // ast_compiles: re-uses the cognition runtime's validateAstCompiles
      // helper. schema_only: trivially passes if no error was thrown.
      if (exp.mode === "ast_compiles") {
        lines.push(`${indent}{`);
        lines.push(`${indent}  // eslint-disable-next-line @typescript-eslint/no-require-imports`);
        lines.push(`${indent}  const { validateAstCompiles } = require("../src/cognition/validate") as { validateAstCompiles: (v: unknown) => Promise<{ ok: boolean; issues: string[] }> };`);
        lines.push(`${indent}  const r = await validateAstCompiles(output);`);
        lines.push(`${indent}  expectations.push({ name: "passes:ast_compiles", ok: r.ok, reason: r.ok ? undefined : r.issues.slice(0, 3).join("; ") });`);
        lines.push(`${indent}}`);
      } else {
        lines.push(`${indent}expectations.push({ name: "passes:schema_only", ok: !error, reason: error });`);
      }
      break;
    case "contains_class_named": {
      const re = JSON.stringify(exp.pattern);
      lines.push(`${indent}{`);
      lines.push(`${indent}  const asString = typeof output === "string" ? output : (output && typeof output === "object" && "content" in (output as object) && typeof (output as {content?:unknown}).content === "string") ? (output as {content:string}).content : Array.isArray(output) ? output.map(f => f && typeof f === "object" && typeof (f as {content?:unknown}).content === "string" ? (f as {content:string}).content : "").join("\\n") : "";`);
      lines.push(`${indent}  const re = new RegExp(${re});`);
      lines.push(`${indent}  // Match \`class FooAdapter\` or \`export class FooAdapter\` declarations.`);
      lines.push(`${indent}  const m = asString.match(/(?:^|\\b)(?:export\\s+)?(?:abstract\\s+)?class\\s+([A-Za-z_][A-Za-z0-9_]*)/);`);
      lines.push(`${indent}  const className = m ? m[1] : null;`);
      lines.push(`${indent}  const ok = className !== null && re.test(className);`);
      lines.push(`${indent}  expectations.push({ name: "contains_class_named", ok, reason: ok ? undefined : (className ? \`class '\${className}' didn't match ${exp.pattern.replace(/`/g, "\\`")}\` : "no class declaration found") });`);
      lines.push(`${indent}}`);
      break;
    }
    case "must_contain_string": {
      const list = JSON.stringify(exp.values);
      lines.push(`${indent}{`);
      lines.push(`${indent}  const asString = typeof output === "string" ? output : JSON.stringify(output);`);
      lines.push(`${indent}  const missing = (${list} as string[]).filter(s => !asString.includes(s));`);
      lines.push(`${indent}  expectations.push({ name: "must_contain_string", ok: missing.length === 0, reason: missing.length === 0 ? undefined : "missing: " + missing.join(", ") });`);
      lines.push(`${indent}}`);
      break;
    }
    case "must_not_contain_string": {
      const list = JSON.stringify(exp.values);
      lines.push(`${indent}{`);
      lines.push(`${indent}  const asString = typeof output === "string" ? output : JSON.stringify(output);`);
      lines.push(`${indent}  const found = (${list} as string[]).filter(s => asString.includes(s));`);
      lines.push(`${indent}  expectations.push({ name: "must_not_contain_string", ok: found.length === 0, reason: found.length === 0 ? undefined : "found forbidden: " + found.join(", ") });`);
      lines.push(`${indent}}`);
      break;
    }
    case "imports_only_from": {
      const list = JSON.stringify(exp.allowed);
      lines.push(`${indent}{`);
      lines.push(`${indent}  const asString = typeof output === "string" ? output : "";`);
      lines.push(`${indent}  const allowed = new Set(${list} as string[]);`);
      // Match `import ... from "x"` and `require("x")`. Return all unique sources.
      lines.push(`${indent}  const importRe = /import\\s+(?:(?:[\\w*{},\\s]+from\\s+)?)['"]([^'"]+)['"]/g;`);
      lines.push(`${indent}  const requireRe = /require\\s*\\(\\s*['"]([^'"]+)['"]\\s*\\)/g;`);
      lines.push(`${indent}  const sources = new Set<string>();`);
      lines.push(`${indent}  let m: RegExpExecArray | null;`);
      lines.push(`${indent}  while ((m = importRe.exec(asString)) !== null) sources.add(m[1]);`);
      lines.push(`${indent}  while ((m = requireRe.exec(asString)) !== null) sources.add(m[1]);`);
      // Allow relative imports ("./..." or "../...") regardless of allowlist.
      lines.push(`${indent}  const violations = [...sources].filter(s => !s.startsWith(".") && !allowed.has(s));`);
      lines.push(`${indent}  expectations.push({ name: "imports_only_from", ok: violations.length === 0, reason: violations.length === 0 ? undefined : "disallowed imports: " + violations.join(", ") });`);
      lines.push(`${indent}}`);
      break;
    }
    case "max_lines":
      lines.push(`${indent}{`);
      lines.push(`${indent}  const asString = typeof output === "string" ? output : JSON.stringify(output);`);
      lines.push(`${indent}  const n = asString.split(/\\r?\\n/).length;`);
      lines.push(`${indent}  expectations.push({ name: "max_lines", ok: n <= ${exp.value}, reason: n <= ${exp.value} ? undefined : \`output has \${n} lines (limit ${exp.value})\` });`);
      lines.push(`${indent}}`);
      break;
    case "min_lines":
      lines.push(`${indent}{`);
      lines.push(`${indent}  const asString = typeof output === "string" ? output : JSON.stringify(output);`);
      lines.push(`${indent}  const n = asString.split(/\\r?\\n/).length;`);
      lines.push(`${indent}  expectations.push({ name: "min_lines", ok: n >= ${exp.value}, reason: n >= ${exp.value} ? undefined : \`output has \${n} lines (need ≥ ${exp.value})\` });`);
      lines.push(`${indent}}`);
      break;
    case "latency_under_ms":
      lines.push(`${indent}expectations.push({ name: "latency_under_ms", ok: duration_ms <= ${exp.value}, reason: duration_ms <= ${exp.value} ? undefined : \`call took \${duration_ms}ms (limit ${exp.value}ms)\` });`);
      break;
  }
}

// ─── Index ──────────────────────────────────────────────────────────────────

function emitIndex(evals: IR.IREvaluation[]): string {
  const lines: string[] = [];
  lines.push("// Generated by MarrowScript compiler. DO NOT EDIT.");
  lines.push("// Phase 16 — evaluation registry.");
  lines.push("");
  for (const ev of evals) {
    lines.push(`import { run as run_${safeName(ev.name)} } from "./${ev.name}";`);
  }
  lines.push("");
  lines.push("export const EVALUATIONS: Record<string, () => Promise<unknown>> = {");
  for (const ev of evals) {
    lines.push(`  ${JSON.stringify(ev.name)}: run_${safeName(ev.name)},`);
  }
  lines.push("};");
  lines.push("");
  lines.push("export function listEvaluations(): string[] {");
  lines.push("  return Object.keys(EVALUATIONS).sort();");
  lines.push("}");
  return lines.join("\n");
}

function emitCLI(evals: IR.IREvaluation[]): string {
  const lines: string[] = [];
  lines.push("// Generated by MarrowScript compiler. DO NOT EDIT.");
  lines.push("// Phase 16 — evaluation CLI.");
  lines.push("//");
  lines.push("// Usage:");
  lines.push("//   npx ts-node bin/evaluate.ts            — run all evaluations");
  lines.push("//   npx ts-node bin/evaluate.ts <name>     — run one evaluation");
  lines.push("//   npx ts-node bin/evaluate.ts --list     — print declared evaluations");
  lines.push("//");
  lines.push("// Exit code 0 = all baselines met, 1 = at least one regression, 2 = error.");
  lines.push("");
  lines.push("import { EVALUATIONS, listEvaluations } from \"../eval\";");
  lines.push("");
  lines.push("interface EvalResultLike {");
  lines.push("  evaluation: string;");
  lines.push("  total: number;");
  lines.push("  passed: number;");
  lines.push("  pass_rate: number;");
  lines.push("  baseline_pass_rate: number;");
  lines.push("  baseline_ok: boolean;");
  lines.push("  cases: { case: string; pass: boolean; expectations: { name: string; ok: boolean; reason?: string }[]; error?: string }[];");
  lines.push("}");
  lines.push("");
  lines.push("async function main() {");
  lines.push("  const args = process.argv.slice(2);");
  lines.push("  if (args.includes(\"--list\")) {");
  lines.push("    for (const n of listEvaluations()) console.log(n);");
  lines.push("    return;");
  lines.push("  }");
  lines.push("  const target = args[0];");
  lines.push("  const names = target ? [target] : listEvaluations();");
  lines.push("  const results: EvalResultLike[] = [];");
  lines.push("  for (const name of names) {");
  lines.push("    const fn = EVALUATIONS[name];");
  lines.push("    if (!fn) {");
  lines.push("      console.error(`No such evaluation: ${name}. Available: ${listEvaluations().join(\", \")}`);");
  lines.push("      process.exit(2);");
  lines.push("    }");
  lines.push("    const r = (await fn()) as EvalResultLike;");
  lines.push("    results.push(r);");
  lines.push("  }");
  lines.push("  // Pretty-print a summary table to stdout. JSON details go to stderr.");
  lines.push("  console.log(`name${\" \".repeat(40)}\\tpass\\ttotal\\trate\\tbaseline\\tok`);");
  lines.push("  for (const r of results) {");
  lines.push("    const pad = (s: string, n: number) => (s + \" \".repeat(n)).slice(0, n);");
  lines.push("    console.log(`${pad(r.evaluation, 44)}\\t${r.passed}\\t${r.total}\\t${(r.pass_rate * 100).toFixed(1)}%\\t${(r.baseline_pass_rate * 100).toFixed(1)}%\\t${r.baseline_ok ? \"v\" : \"x\"}`);");
  lines.push("  }");
  lines.push("  // For each failed expectation, print a one-liner so CI logs are useful.");
  lines.push("  for (const r of results) {");
  lines.push("    for (const c of r.cases) {");
  lines.push("      if (c.pass) continue;");
  lines.push("      console.log(`  x ${r.evaluation} / ${c.case}${c.error ? \": \" + c.error : \"\"}`);");
  lines.push("      for (const e of c.expectations) {");
  lines.push("        if (!e.ok) console.log(`    - ${e.name}: ${e.reason || \"(no reason)\"}`);");
  lines.push("      }");
  lines.push("    }");
  lines.push("  }");
  lines.push("  const anyFail = results.some(r => !r.baseline_ok);");
  lines.push("  process.exit(anyFail ? 1 : 0);");
  lines.push("}");
  lines.push("");
  lines.push("main().catch(err => {");
  lines.push("  console.error(\"evaluate failed:\", err);");
  lines.push("  process.exit(2);");
  lines.push("});");
  // Reference the registry to silence unused-import warnings in case the
  // user's tsconfig is stricter than ours.
  lines.push("");
  lines.push(`void EVALUATIONS;`);
  return lines.join("\n");
}

function safeName(name: string): string {
  return name.replace(/[^A-Za-z0-9_]/g, "_");
}

// Mark the emitter file referenced by the IR symbol so unused-import linters
// don't flag the IR import when no evaluations exist.
void evaluationsNeeded;
